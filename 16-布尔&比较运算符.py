# 比较运算符的使用
num1=90
num2=98
 
num=num1>num2
print(f"num1>num2的结果是：{num},类型是{type(num1>num2)}")

num=num1<num2
print(f"num1<num2的结果是：{num},类型是{type(num)}")

num=num1>=num2
print(f"num1>=num2的结果是：{num},类型是{type(num)}")

num=num1<=num2
print(f"num1<=num2的结果是：{num},类型是{type(num)}")

num=num1!=num2
print(f"num1!=num2的结果是：{num},类型是{type(num)}")

num=num1==num2
print(f"num1==num2的结果是：{num},类型是{type(num)}")
